export function getRandomQuote(
  selectedGenres: string[],
  selectedDifficulties: string[],
  usedQuoteIds: string[] = [],
  customQuotes: Quote[] = []
): Quote | null {
  const pool = [...INITIAL_QUOTES, ...customQuotes].filter((q) => {
    const genreMatch = selectedGenres.length === 0 || selectedGenres.includes(q.genre);
    const diffMatch = selectedDifficulties.length === 0 || selectedDifficulties.includes(q.difficulty);
    const notUsed = !usedQuoteIds.includes(q.id);
    return genreMatch && diffMatch && notUsed;
  });

  if (pool.length === 0) {
    const fallbackPool = [...INITIAL_QUOTES, ...customQuotes].filter((q) => {
      const genreMatch = selectedGenres.length === 0 || selectedGenres.includes(q.genre);
      const diffMatch = selectedDifficulties.length === 0 || selectedDifficulties.includes(q.difficulty);
      return genreMatch && diffMatch;
    });
    if (fallbackPool.length === 0) return null;
    return fallbackPool[Math.floor(Math.random() * fallbackPool.length)];
  }

  return pool[Math.floor(Math.random() * pool.length)];
}
